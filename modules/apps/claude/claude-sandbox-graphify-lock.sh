# claude-sandbox-graphify-lock [<version> [<extras>]]
#
# Prints the hashed pip lock the graphify sidecar installs
# from (modules/apps/claude/claude-sandbox-graphify-requirements.txt): graphifyy
# <version> with the comma-separated pip <extras> and every dependency, pinned
# to an exact version with sha256 hashes, resolved for the graphify image's
# Python on x86_64 Linux. The defaults are the current
# programs.claudeSandbox.graphifyVersion / graphifyExtras, so to bump:
#   claude-sandbox-graphify-lock <new version> [<extras>] \
#     > modules/apps/claude/claude-sandbox-graphify-requirements.txt
# then set the options to match (the build checks the lock's spec line).
# Expects GRAPHIFY_VERSION, GRAPHIFY_EXTRAS and GRAPHIFY_PYTHON (e.g. 3.12).
version="${1:-$GRAPHIFY_VERSION}"
extras="${2:-$GRAPHIFY_EXTRAS}"
spec="graphifyy[$extras]==$version"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
echo "$spec" > "$tmp/requirements.in"

echo "# spec: $spec"
echo "# python: $GRAPHIFY_PYTHON x86_64-unknown-linux-gnu"
echo "# Generated by claude-sandbox-graphify-lock (see UPDATES.md); don't edit by hand."
uv pip compile "$tmp/requirements.in" \
  --python-version "$GRAPHIFY_PYTHON" \
  --python-platform x86_64-unknown-linux-gnu \
  --generate-hashes \
  --no-header \
  | sed "s|$tmp/requirements.in|$spec|"
